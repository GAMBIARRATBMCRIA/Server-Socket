    private void tableInterfaceMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableInterfaceMousePressed
        int linha = tableInterface.getSelectedRow();
        int coluna = tableInterface.getSelectedColumn();
        JCheckBox box = new JCheckBox("", (boolean) tableInterface.getValueAt(linha, 7));
        boolean marcado_envio = !box.isSelected();

        labelInfo.setText(" ");

        if (coluna == 3) {
            labelMaquina.setText("Setor:" + tableInterface.getValueAt(linha, 3).toString());
        } else if (coluna == 4) {
            JLabel label = (JLabel) tableInterface.getValueAt(linha, 4);
            labelMaquina.setText("Bancada:" + label.getText());
        } else {
            labelMaquina.setText("Mac:" + tableInterface.getValueAt(linha, 1).toString());
            ExecucaoAtividadesTela.selectTablePane(tableInterface.getValueAt(linha, 1).toString());
        }

        if (coluna == 7) {
            ExecucaoAtividadesTela.setHabilitarEnvioMaquina(marcado_envio, labelMaquina.getText().replaceAll("Mac:", ""));
        }

        if (labelMaquina.getText().contains("=")) {
            enviarButton.setEnabled(false);
            labelInfo.setText("Desabilitado para enviar comando");

        } else {
            DefaultTableModel modelo = (DefaultTableModel) tableInterface.getModel();
            Boolean habilitado = (Boolean) modelo.getValueAt(linha, 7);

            if (habilitado) {

                enviarButton.setEnabled(true);
                labelInfo.setText(" ");
            } else {
                enviarButton.setEnabled(false);
                labelInfo.setText("Desabilitado para enviar comando");
            }

        }

    }//GEN-LAST:event_tableInterfaceMousePressed

