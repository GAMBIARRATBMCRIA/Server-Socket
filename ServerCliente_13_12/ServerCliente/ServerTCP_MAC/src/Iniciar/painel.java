    private void tableaServicosMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableaServicosMousePressed
        btnPara.setEnabled(false);
        int linha = tableaServicos.getSelectedRow();
        labelNome.setText(tableaServicos.getValueAt(linha, 1).toString());
        labelNomeExi.setText(tableaServicos.getValueAt(linha, 0).toString());
        String status = tableaServicos.getValueAt(linha, 2).toString();

        labelStatus.setText(status);

        if (status.contains("Stopped")) {
            btnPara.setEnabled(true);
            btnPara.setText("Iniciar");

        } else if (status.replaceAll(" ", "").isEmpty()) {
            btnPara.setEnabled(false);
            btnPara.setText("Iniciar");
        } else {
            btnPara.setEnabled(true);
            btnPara.setText("Parar");
        }
    }//GEN-LAST:event_tableaServicosMousePressed

